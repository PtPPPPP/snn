import {index,integer,real,sqliteTable,text,uniqueIndex} from "drizzle-orm/sqlite-core";
export const interviewInvitations=sqliteTable("interview_invitations",{
 id:text("id").primaryKey(),
 formVersion:text("form_version").notNull(),
 codeHash:text("code_hash").notNull(),
 applicantName:text("applicant_name").notNull(),
 studentId:text("student_id").notNull(),
 department:text("department").notNull().default(""),
 year:text("year").notNull().default(""),
 createdAt:text("created_at").notNull(),
 codeIssuedAt:text("code_issued_at").notNull(),
 expiresAt:text("expires_at").notNull(),
 revokedAt:text("revoked_at"),
 issuedByUserId:text("issued_by_user_id").notNull(),
},table=>[
 uniqueIndex("uniq_interview_invitation_code").on(table.codeHash),
 uniqueIndex("uniq_interview_invitation_student").on(table.formVersion,table.studentId),
]);
export const interviewIdentities=sqliteTable("interview_identities",{
 id:text("id").primaryKey(),
 formVersion:text("form_version").notNull(),
 userId:text("user_id").notNull(),
 deviceHash:text("device_hash"),
 applicantName:text("applicant_name").notNull(),
 studentId:text("student_id").notNull(),
 department:text("department").notNull().default(""),
 year:text("year").notNull().default(""),
 createdAt:text("created_at").notNull(),
 invitationId:text("invitation_id").references(()=>interviewInvitations.id),
 startedAt:text("started_at"),
},table=>[
 uniqueIndex("uniq_interview_identity_user").on(table.formVersion,table.userId),
 uniqueIndex("uniq_interview_identity_device").on(table.formVersion,table.deviceHash),
 uniqueIndex("uniq_interview_identity_student").on(table.formVersion,table.studentId),
 uniqueIndex("uniq_interview_identity_invitation").on(table.invitationId),
]);
export const interviewSubmissions=sqliteTable("interview_submissions",{
 id:text("id").primaryKey(),
 formVersion:text("form_version").notNull(),
 applicantName:text("applicant_name").notNull(),
 studentId:text("student_id").notNull(),
 department:text("department").notNull().default(""),
 year:text("year").notNull().default(""),
 track:text("track").notNull(),
 questionBankVersion:text("question_bank_version").notNull().default("snn-entry-2026-v1"),
 rubricsJson:text("rubrics_json").notNull().default("{}"),
 questionsJson:text("questions_json").notNull(),
 answersJson:text("answers_json").notNull(),
 submittedAt:text("submitted_at").notNull(),
 gradesJson:text("grades_json").notNull().default("{}"),
 totalScore:real("total_score"),
 feedback:text("feedback").notNull().default(""),
 reviewedBy:text("reviewed_by").notNull().default(""),
 reviewedAt:text("reviewed_at"),
 identityId:text("identity_id").references(()=>interviewIdentities.id),
 reviewRevision:integer("review_revision").notNull().default(0),
 reviewedByUserId:text("reviewed_by_user_id"),
 startedAt:text("started_at"),
 elapsedSeconds:integer("elapsed_seconds"),
 resultStatus:text("result_status").notNull().default("pending"),
 resultMessage:text("result_message").notNull().default(""),
 resultPublishedAt:text("result_published_at"),
 resultRevision:integer("result_revision").notNull().default(0),
 candidateReply:text("candidate_reply"),
 candidateRepliedAt:text("candidate_replied_at"),
},table=>[
 uniqueIndex("uniq_interview_version_student").on(table.formVersion,table.studentId),
 uniqueIndex("uniq_interview_submission_identity").on(table.identityId),
]);
export const interviewAuditEvents=sqliteTable("interview_audit_events",{
 id:text("id").primaryKey(),
 identityId:text("identity_id").references(()=>interviewIdentities.id),
 submissionId:text("submission_id").references(()=>interviewSubmissions.id),
 invitationId:text("invitation_id").references(()=>interviewInvitations.id),
 action:text("action").notNull(),
 actorUserId:text("actor_user_id").notNull(),
 actorEmail:text("actor_email").notNull(),
 detailsJson:text("details_json").notNull().default("{}"),
 createdAt:text("created_at").notNull(),
},table=>[index("idx_interview_audit_submission").on(table.submissionId,table.createdAt)]);
