type Anchor = [label:string,full:string,partial:string,zero:string];
function rubric(focus:string,example:string,anchors:Anchor[],common=false):InterviewRubric{
 const weights=anchors.length===2?[5,5]:common?[3,3,2,2]:[5,5,5,5];
 const criteria:InterviewCriterion[]=anchors.map(([label,full,partial,zero],i)=>({id:"p"+(i+1),label,points:weights[i],full,partial,zero}));
 return {focus,example,criteria};
}
